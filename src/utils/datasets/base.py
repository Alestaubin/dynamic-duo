"""
base.py
=======
Shared machinery for the dataset classes in this package.

Every dataset class is a `ShiftDataset`: it knows where its data lives (a key in cfgs/global.yaml),
verifies the on-disk layout (`check()`), and hands out loaders with ONE contract, the same one
src/tta/dynamic_duo.py already consumes: batches of `(list[PIL.Image], LongTensor)` with no
preprocessing applied (each model applies its own transform), labels in 0..num_classes-1.

Two things differ from `torchvision.datasets.ImageFolder`, on purpose:
  * Classes come from an explicit wnid list, not from whatever folders exist. A missing class folder
    is an error here; with ImageFolder it silently shifts every later label by one.
  * 200-class datasets (ImageNet-R/A) carry a `class_mask`: the indices of their classes inside the
    1000-way logits. Scores are `logits[:, class_mask]` (use `apply_class_mask`), and anything that
    depends on the class count (log K, nuclear norm) must use `num_classes`, not 1000.
"""

from __future__ import annotations

import collections
from abc import ABC, abstractmethod
from pathlib import Path
from typing import ClassVar, Mapping, Sequence

import torch
from torch.utils.data import DataLoader, Dataset, Subset
from torchvision.datasets.folder import IMG_EXTENSIONS, default_loader, make_dataset

from src.utils.config import GlobalConfig
from src.utils.datasets.staging import is_archive, list_archive_files, peek_staged, stage_archive

CLASS_LISTS = Path(__file__).parent / "class_lists"


class DatasetLayoutError(RuntimeError):
    """The data on disk does not have the layout the dataset class expects."""


def read_wnids(name: str) -> list[str]:
    """One of class_lists/imagenet_{1k,r,a}_wnids.txt (generated by third_party/extract_assets.py)."""
    return (CLASS_LISTS / f"imagenet_{name}_wnids.txt").read_text().split()


def pil_collate(batch):
    images, labels = zip(*batch)
    return list(images), torch.tensor(labels)


def worker_init(_worker_id: int) -> None:
    """One CPU thread per DataLoader worker: with torch's default every worker spawns a thread per core."""
    torch.set_num_threads(1)


def make_loader(
    ds: Dataset, *, batch_size: int, shuffle: bool = True, workers: int = 4, pin_memory: bool = False,
    num_samples: int | None = None, seed: int | None = None, collate_fn=pil_collate,
) -> DataLoader:
    """DataLoader over `ds`, optionally on a random `num_samples` subset.

    Subset selection and batch order are both drawn from generators seeded with `seed`, exactly as
    src/utils/data.py::load_imagenetC does, so identical (dataset, num_samples, seed, batch_size)
    reproduce the same batch sequence (this is what makes cached logits safe to replay).
    """
    if num_samples is not None:
        n = min(num_samples, len(ds))
        gen = torch.Generator().manual_seed(seed) if seed is not None else None
        ds = Subset(ds, torch.randperm(len(ds), generator=gen)[:n].tolist())
    gen = torch.Generator().manual_seed(seed) if seed is not None else None
    return DataLoader(
        ds, batch_size=batch_size, shuffle=shuffle, num_workers=workers, pin_memory=pin_memory,
        collate_fn=collate_fn, generator=gen, worker_init_fn=worker_init if workers > 0 else None,
    )


class WnidFolder(Dataset):
    """Images under `root/<class_dir>/*`, labelled by `class_dirs.index(class_dir)`.

    `class_dirs` is an explicit, ordered list of folder names (wnids, or the digits 0..999 for
    ImageNet-V2); every one of them must exist. With `strict`, no OTHER sub-directory may exist either
    (a different class subset than the one the label mapping assumes). Sample order matches
    torchvision's ImageFolder. Non-directory entries (README.txt) are ignored.
    """

    def __init__(self, root: Path, class_dirs: Sequence[str], strict: bool = False, hint: str = ""):
        self.root = Path(root)
        self.class_dirs = list(class_dirs)
        if not self.root.is_dir():
            raise DatasetLayoutError(f"{self.root} is not a directory")
        missing = [c for c in self.class_dirs if not (self.root / c).is_dir()]
        if missing:
            raise DatasetLayoutError(
                f"{self.root} is missing {len(missing)}/{len(self.class_dirs)} class folders "
                f"(first few: {missing[:3]}). Expected one folder per class directly under that path. {hint}".rstrip()
            )
        if strict:
            extra = sorted({p.name for p in self.root.iterdir() if p.is_dir()} - set(self.class_dirs))
            if extra:
                raise DatasetLayoutError(f"{self.root} has {len(extra)} class folders outside the expected set "
                                         f"(first few: {extra[:3]}). {hint}".rstrip())
        self.samples = make_dataset(
            str(self.root), {c: i for i, c in enumerate(self.class_dirs)}, extensions=IMG_EXTENSIONS,
        )
        if not self.samples:
            raise DatasetLayoutError(f"no images found under {self.root}")

    @property
    def per_class(self) -> dict[str, int]:
        counts = collections.Counter(label for _, label in self.samples)
        return {c: counts.get(i, 0) for i, c in enumerate(self.class_dirs)}

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, i: int):
        path, label = self.samples[i]
        return default_loader(path), label


class FileList(Dataset):
    """An explicit (path, label) list; used where the selection itself is the dataset."""

    def __init__(self, samples: list[tuple[str, int]]):
        self.samples = samples

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, i: int):
        path, label = self.samples[i]
        return default_loader(path), label


class ShiftDataset(ABC):
    name: ClassVar[str]
    config_key: ClassVar[str]               # key under `paths:` in cfgs/global.yaml
    already_224: ClassVar[bool] = False     # images are already 224x224 centre crops (ImageNet-C, CCC)

    num_classes: int = 1000                 # effective K after masking
    class_mask: list[int] | None = None     # indices into the 1000-way logits; None = all 1000

    def __init__(self, root: str | Path):
        """`root` is a directory, or an archive (.tar/.tar.gz/.zip) that is extracted to node-local
        storage the first time `self.root` is read (see staging.py)."""
        self.source = Path(root)
        self._root: Path | None = None if is_archive(self.source) else self.source

    @property
    def root(self) -> Path:
        if self._root is None:
            self._root = stage_archive(self.source)
        return self._root

    @property
    def archive_backed(self) -> bool:
        return is_archive(self.source)

    @classmethod
    def from_config(cls, g: GlobalConfig, **kwargs) -> "ShiftDataset":
        return cls(g.path(cls.config_key), **kwargs)

    @abstractmethod
    def torch_dataset(self) -> Dataset:
        """Map-style dataset yielding (PIL.Image, label). Raises DatasetLayoutError on a bad layout."""

    def __len__(self) -> int:
        return len(self.torch_dataset())

    def check(self) -> dict:
        """Verify the layout and return a short summary; raises DatasetLayoutError otherwise."""
        return {"images": len(self.torch_dataset()), "classes": self.num_classes}

    def objective_logits(self, logits: torch.Tensor, mode: str) -> torch.Tensor:
        """The logits the TTA objective sees: the masked ones ("masked", the default) or all 1000 ("full").
        Accuracy/ECE always use `apply_class_mask`. Only differs for the 200-class datasets."""
        if mode not in ("masked", "full"):
            raise ValueError(f"objective logits mode must be 'masked' or 'full', got {mode!r}")
        return self.apply_class_mask(logits) if mode == "masked" else logits

    def loader(self, batch_size: int, num_samples: int | None = None, seed: int | None = None,
               workers: int = 4, pin_memory: bool = False, shuffle: bool = True, collate_fn=pil_collate) -> DataLoader:
        """`collate_fn` turns a list of (PIL image, label) into a batch; the default keeps PIL images, a custom one
        (e.g. src.experiments.members.PairCollate) can run the models' preprocessing inside the workers."""
        return make_loader(
            self.torch_dataset(), batch_size=batch_size, shuffle=shuffle, workers=workers,
            pin_memory=pin_memory, num_samples=num_samples, seed=seed, collate_fn=collate_fn,
        )

    def apply_class_mask(self, logits: torch.Tensor) -> torch.Tensor:
        """(B, 1000) model logits -> (B, num_classes) scores aligned with this dataset's labels."""
        return logits if self.class_mask is None else logits[:, self.class_mask]

    def describe(self) -> str:
        return f"{self.name} ({self.source})"


class FolderDataset(ShiftDataset):
    """A dataset laid out as <root>/<class_dir>/<images>, with a known class list and known counts.

    The counts are the ones documented for the real data; they are asserted every time the dataset is
    built (and by `check()` straight from the archive listing, without extracting). Pass
    `verify_counts=False` only for synthetic test trees.
    """

    expected_images: ClassVar[int | None] = None
    expected_per_class: ClassVar[int | None] = None
    strict_classes: ClassVar[bool] = True
    class_hint: ClassVar[str] = ""

    def __init__(self, root: str | Path, verify_counts: bool = True):
        super().__init__(root)
        self.verify_counts = verify_counts

    @abstractmethod
    def class_dirs(self) -> list[str]:
        """Folder names in label order (label i is class_dirs()[i])."""

    def _verify(self, n_images: int, per_class: Mapping[str, int], where: str) -> None:
        if not self.verify_counts:
            return
        if self.expected_images is not None and n_images != self.expected_images:
            raise DatasetLayoutError(f"{where}: {n_images:,} images, expected {self.expected_images:,}")
        if self.expected_per_class is not None:
            bad = {c: n for c, n in per_class.items() if n != self.expected_per_class}
            if bad:
                raise DatasetLayoutError(f"{where}: {len(bad)} classes do not have {self.expected_per_class} "
                                         f"images (e.g. {dict(list(bad.items())[:3])})")

    def torch_dataset(self) -> WnidFolder:
        ds = WnidFolder(self.root, self.class_dirs(), strict=self.strict_classes, hint=self.class_hint)
        self._verify(len(ds), ds.per_class, str(self.root))
        return ds

    def _check_archive(self) -> dict:
        """The same checks as torch_dataset(), from the archive's member list (nothing is extracted)."""
        files = [f[2:] if f.startswith("./") else f for f in list_archive_files(self.source)]
        per_class: collections.Counter = collections.Counter()
        tops = set()
        for f in files:
            parts = f.split("/")
            if len(parts) >= 3 and f.lower().endswith(IMG_EXTENSIONS):
                tops.add(parts[0])
                per_class[parts[1]] += 1
        if len(tops) != 1:
            raise DatasetLayoutError(f"{self.source.name}: expected one top-level directory, found {sorted(tops)}")
        expected = self.class_dirs()
        if self.strict_classes and set(per_class) != set(expected):
            raise DatasetLayoutError(
                f"{self.source.name}: class folders differ from the expected set "
                f"(only in archive: {sorted(set(per_class) - set(expected))[:3]}, "
                f"only expected: {sorted(set(expected) - set(per_class))[:3]}). {self.class_hint}".rstrip())
        self._verify(sum(per_class.values()), {c: per_class.get(c, 0) for c in expected}, self.source.name)
        return {"images": sum(per_class.values()), "classes": self.num_classes, "where": "archive listing (not extracted)"}

    def check(self, stage: bool = False) -> dict:
        """Layout + count assertions. An archive that is not extracted yet is verified from its member list
        (works on a login node); `stage=True` extracts it (needs $SLURM_TMPDIR) and checks the files."""
        if self.archive_backed and not stage and peek_staged(self.source) is None:
            return self._check_archive()
        ds = self.torch_dataset()
        return {"images": len(ds), "classes": self.num_classes, "where": str(self.root)}
